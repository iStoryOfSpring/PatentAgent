export type TranslationParams = Record<string, string | number>;

function interpolate(value: string, params?: TranslationParams): string {
  if (!params) return value;
  return value.replace(/\{\{(\w+)\}\}/g, (match, key: string) => (
    Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : match
  ));
}

export function isLocale(value: unknown): value is Locale {
  return value === "zh-CN" || value === "en-US";
}

export function localeFromLanguage(value: unknown): Locale | null {
  if (typeof value !== "string") return null;
  const language = value.trim().toLowerCase();
  if (language === "zh" || language.startsWith("zh-")) return "zh-CN";
  if (language === "en" || language.startsWith("en-")) return "en-US";
  return null;
}

export function localeFromNavigator(languages?: readonly string[]): Locale {
  const candidates = languages || (() => {
    try {
      const browserNavigator = typeof navigator !== "undefined" ? navigator : undefined;
      return browserNavigator?.languages?.length ? browserNavigator.languages : browserNavigator?.language ? [browserNavigator.language] : [];
    } catch {
      return [];
    }
  })();
  for (const language of candidates) {
    const locale = localeFromLanguage(language);
    if (locale) return locale;
  }
  return DEFAULT_LOCALE;
}

export function readStoredLocale(): Locale | null {
  try {
    const value = typeof window !== "undefined" ? window.localStorage.getItem(LOCALE_STORAGE_KEY) : null;
    return isLocale(value) ? value : null;
  } catch {
    return null;
  }
}

export function persistLocale(locale: Locale): void {
  if (!isLocale(locale)) return;
  try {
    if (typeof window !== "undefined") window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
  } catch {
    // A restricted storage context should not prevent an in-memory switch.
  }
}

export function getInitialLocale(): Locale {
  return readStoredLocale() || localeFromNavigator();
}

export function translate(key: string, locale: Locale = DEFAULT_LOCALE, params?: TranslationParams): string {
  const localized = locale === "en-US" ? enUS[key as TranslationKey] : undefined;
  const value = localized ?? zhCN[key as TranslationKey] ?? key;
  return interpolate(value, params);
}

interface I18nContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: <K extends TranslationKey>(key: K, params?: TranslationParams) => string;
}

const defaultContext: I18nContextValue = {
  locale: DEFAULT_LOCALE,
  setLocale: () => undefined,
  t: (key, params) => translate(key, DEFAULT_LOCALE, params),
};

const I18nContext = createContext<I18nContextValue>(defaultContext);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(getInitialLocale);
  const setLocale = (next: Locale) => {
    if (!isLocale(next)) return;
    setLocaleState(next);
    persistLocale(next);
  };

  useEffect(() => {
    if (typeof document !== "undefined") document.documentElement.lang = locale;
  }, [locale]);

  const value = useMemo<I18nContextValue>(() => ({
    locale,
    setLocale,
    t: (key, params) => translate(key, locale, params),
  }), [locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}
